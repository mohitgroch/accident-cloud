from typing import Optional, Dict, Any, Union
from pydantic import BaseModel, Field, field_validator
import datetime

class SensorSummary(BaseModel):
    """
    Optional sensor telemetry captured during impact window:
    Peak resultant acceleration, jerk value, gyroscope tilt, etc.
    """
    peak_accel: Optional[float] = Field(None, description="Peak resultant acceleration in m/s^2 or g")
    peak_jerk: Optional[float] = Field(None, description="Calculated jerk in m/s^3")
    gyro_x: Optional[float] = None
    gyro_y: Optional[float] = None
    gyro_z: Optional[float] = None
    extra: Optional[Dict[str, Any]] = None

class ContractARequestMetadata(BaseModel):
    """
    Contract A — Pi -> Cloud
    Validates metadata fields transmitted alongside the binary video clip.
    """
    event_id: str = Field(..., description="Unique event identifier generated by Member 1 at trigger time")
    timestamp: str = Field(..., description="ISO 8601 timestamp of trigger (e.g. 2026-11-11T00:46:13Z)")
    gps_lat: Optional[float] = Field(None, description="GPS Latitude, or null if GPS lock was lost")
    gps_long: Optional[float] = Field(None, description="GPS Longitude, or null if GPS lock was lost")
    sensor_summary: Optional[Union[SensorSummary, Dict[str, Any], str]] = Field(
        None, description="Optional peak resultant acceleration / jerk telemetry"
    )

    @field_validator("timestamp")
    @classmethod
    def validate_iso_timestamp(cls, v: str) -> str:
        # Check basic ISO 8601 parsing
        try:
            # Replace Z with +00:00 for fromisoformat compatibility in Python <= 3.10
            cleaned = v.replace("Z", "+00:00")
            datetime.datetime.fromisoformat(cleaned)
        except Exception:
            # We don't fail hard to keep Pi fault tolerance, but we flag if completely garbage
            if not v or len(v) < 8:
                raise ValueError(f"Invalid timestamp format: {v}. Expected ISO 8601 string.")
        return v

