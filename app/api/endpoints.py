@router.post(
    "/api/v1/detect",
    response_model=ContractBResponse,
    status_code=status.HTTP_200_OK,
    summary="Accident Detection Endpoint (Contract A -> Contract B)",
    description=(
        "Receives video clip, timestamp, GPS coordinates, and sensor summary from the Raspberry Pi (Contract A), "
        "runs AI verification, and returns the confirmed verdict, confidence, and status (Contract B)."
    ),
    tags=["Accident Detection"]
)
async def detect_accident(
    event_id: str = Form(..., description="Unique event identifier generated by Member 1 at trigger time"),
    timestamp: str = Form(..., description="ISO 8601 event timestamp (e.g. 2026-11-11T00:46:13Z)"),
    video_clip: UploadFile = File(..., description="Binary video file (.mp4, .avi, etc.) captured by Member 2"),
    gps_lat: Optional[str] = Form(None, description="GPS Latitude float or empty string if no GPS lock"),
    gps_long: Optional[str] = Form(None, description="GPS Longitude float or empty string if no GPS lock"),
    sensor_summary: Optional[str] = Form(None, description="JSON string with peak accel, jerk, and gyro readings"),
):
    start_time = time.time()
    logger = get_logger(event_id)
    logger.info(f"Received detection request for event_id: '{event_id}' | filename: '{video_clip.filename}'")

    # 1. Parse & validate GPS floats safely (handles null, empty string, or "None")
    lat_val: Optional[float] = None
    long_val: Optional[float] = None
    try:
        if gps_lat is not None and gps_lat.strip() and gps_lat.lower() not in ("none", "null"):
            lat_val = float(gps_lat.strip())
        if gps_long is not None and gps_long.strip() and gps_long.lower() not in ("none", "null"):
            long_val = float(gps_long.strip())
    except ValueError as e:
        logger.warning(f"GPS parsing warning for {event_id}: {e}. Proceeding with GPS as None.")
        lat_val, long_val = None, None

    # 2. Parse sensor summary JSON safely if provided
    sensor_dict: Optional[Dict[str, Any]] = None
    if sensor_summary and sensor_summary.strip():
        try:
            sensor_dict = json.loads(sensor_summary)
        except Exception as e:
            logger.warning(f"Failed to parse sensor_summary JSON for {event_id}: {e}")
            sensor_dict = {"raw_sensor_text": sensor_summary}

    # 3. Validate Contract A metadata schema
    try:
        metadata = ContractARequestMetadata(
            event_id=event_id,
            timestamp=timestamp,
            gps_lat=lat_val,
            gps_long=long_val,
            sensor_summary=sensor_dict
        )
    except Exception as validation_err:
        logger.error(f"Contract A validation error on {event_id}: {validation_err}")
        # Return explicit Contract B error to prevent Member 1 crash
        return ContractBResponse.error(
            event_id=event_id,
            detail=f"Malformed metadata: {str(validation_err)}"
        )

    # 4. Save uploaded video to temporary disk location for inference
    temp_video_path = Path(settings.UPLOAD_DIR) / f"{event_id}_{int(start_time)}_{video_clip.filename or 'clip.mp4'}"
    temp_video_path.parent.mkdir(parents=True, exist_ok=True)

    bytes_written = 0
    try:
        content = await video_clip.read()
        bytes_written = len(content)

        if bytes_written == 0:
            logger.error(f"Received empty (0-byte) video clip for {event_id}")
            return ContractBResponse.error(
                event_id=event_id,
                detail="Received empty (0-byte) video file. Upload may have been truncated or dropped."
            )

        with open(temp_video_path, "wb") as f:
            f.write(content)

        logger.info(f"Saved video clip to '{temp_video_path}' ({bytes_written} bytes)")

    except Exception as upload_err:
        logger.exception(f"Error handling video upload for {event_id}: {upload_err}")
        return ContractBResponse.error(
            event_id=event_id,
            detail=f"Failed to process video upload: {str(upload_err)}"
        )

    # 5. Execute inference under timeout protection
    try:
        gps_dict = {"lat": lat_val, "long": long_val} if lat_val is not None else None
        
        verdict, confidence, exec_status, diag = await inference_manager.execute_inference_with_timeout(
            video_path=str(temp_video_path),
            sensor_summary=sensor_dict,
            gps_info=gps_dict,
            event_id=event_id
        )

        latency_ms = round((time.time() - start_time) * 1000, 2)
        logger.info(
            f"Completed processing for {event_id} in {latency_ms}ms: "
            f"status='{exec_status}', verdict={verdict}, confidence={confidence}"
        )

        # 6. Formulate strict Contract B response
        if exec_status == "timeout":
            response = ContractBResponse.timeout_response(event_id=event_id, detail=diag)
        elif exec_status == "error":
            response = ContractBResponse.error(event_id=event_id, detail=diag)
        else:
            response = ContractBResponse.ok(
                event_id=event_id,
                accident_confirmed=verdict,
                confidence=confidence,
                detail=diag
            )

        # Record event in audit log
        audit_record = {
            "event_id": event_id,
            "timestamp": timestamp,
            "received_at": datetime.now(timezone.utc).isoformat(),
            "verdict": response.accident_confirmed,
            "confidence": response.confidence,
            "status": response.status,
            "latency_ms": latency_ms,
            "video_bytes": bytes_written,
            "has_gps": lat_val is not None
        }
        RECENT_EVENTS.append(audit_record)
        if len(RECENT_EVENTS) > MAX_RECENT_EVENTS:
            RECENT_EVENTS.pop(0)

        return response

    finally:
        # 7. Cleanup temp file if configured
        if settings.CLEANUP_TEMP_FILES and temp_video_path.exists():
            try:
                os.remove(temp_video_path)
            except Exception as clean_err:
                logger.warning(f"Failed to delete temp video {temp_video_path}: {clean_err}")

@router.get("/api/v1/events/recent", tags=["Monitoring"])
async def get_recent_events(limit: int = Query(20, ge=1, le=100)):
    """Retrieve recent processed events, verdicts, and latencies for validation."""
    return {
        "count": len(RECENT_EVENTS),
        "events": RECENT_EVENTS[-limit:]
    }

@router.post("/api/v1/admin/mode", tags=["Admin"])
async def set_inference_mode(
    mode: str = Query(..., description="Target mode: 'stub' (Phase 1) or 'model' (Phase 2)")
):
    """Dynamically toggle inference mode without restarting the server."""
    try:
        inference_manager.set_mode(mode)
        return {
            "status": "success",
            "active_mode": inference_manager.mode,
            "message": f"Inference mode updated to '{inference_manager.mode}'"
        }
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

